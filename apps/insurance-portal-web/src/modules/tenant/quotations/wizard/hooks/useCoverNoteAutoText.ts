import { useEffect, useRef } from 'react';
import type { UseFormReturn } from 'react-hook-form';
import type { QuotationFormSchemaValues } from '../../schemas';
import {
  buildDefaultCoverNoteDescription,
  buildDefaultOperativeClause,
} from '../utils/coverNoteText';

interface UseCoverNoteAutoTextArgs {
  form: UseFormReturn<QuotationFormSchemaValues>;
  productName: string | null | undefined;
  validFrom: string | null | undefined;
  validUntil: string | null | undefined;
  isHydrating?: boolean;
}

/**
 * Keeps `cover_note_desc` and `operative_clause` in sync with the selected
 * product and cover period, without clobbering a value the user has typed
 * themselves. A field is only (re)generated while it is empty or still holds
 * exactly the text this hook previously wrote into it.
 */
export function useCoverNoteAutoText({
  form,
  productName,
  validFrom,
  validUntil,
  isHydrating = false,
}: UseCoverNoteAutoTextArgs) {
  const generatedCoverNoteDesc = buildDefaultCoverNoteDescription(
    productName,
    validFrom,
    validUntil,
  );
  const generatedOperativeClause = buildDefaultOperativeClause(
    productName,
    validFrom,
    validUntil,
  );

  const coverNoteDescGeneratedRef = useRef<string | null>(null);
  const operativeClauseGeneratedRef = useRef<string | null>(null);

  useEffect(() => {
    if (isHydrating || generatedCoverNoteDesc === null) return;
    const currentValue = form.getValues('cover_note_desc') ?? '';
    const isEmpty = !currentValue.trim();
    const wasAutoGenerated =
      coverNoteDescGeneratedRef.current !== null &&
      currentValue === coverNoteDescGeneratedRef.current;
    if (isEmpty || wasAutoGenerated) {
      if (currentValue !== generatedCoverNoteDesc) {
        form.setValue('cover_note_desc', generatedCoverNoteDesc, {
          shouldValidate: true,
          shouldDirty: true,
        });
      }
      coverNoteDescGeneratedRef.current = generatedCoverNoteDesc;
    }
  }, [form, generatedCoverNoteDesc, isHydrating]);

  useEffect(() => {
    if (isHydrating || generatedOperativeClause === null) return;
    const currentValue = form.getValues('operative_clause') ?? '';
    const isEmpty = !currentValue.trim();
    const wasAutoGenerated =
      operativeClauseGeneratedRef.current !== null &&
      currentValue === operativeClauseGeneratedRef.current;
    if (isEmpty || wasAutoGenerated) {
      if (currentValue !== generatedOperativeClause) {
        form.setValue('operative_clause', generatedOperativeClause, {
          shouldValidate: true,
          shouldDirty: true,
        });
      }
      operativeClauseGeneratedRef.current = generatedOperativeClause;
    }
  }, [form, generatedOperativeClause, isHydrating]);

  const resetCoverNoteDescToDefault = () => {
    if (generatedCoverNoteDesc === null) return;
    form.setValue('cover_note_desc', generatedCoverNoteDesc, {
      shouldValidate: true,
      shouldDirty: true,
    });
    coverNoteDescGeneratedRef.current = generatedCoverNoteDesc;
  };

  const resetOperativeClauseToDefault = () => {
    if (generatedOperativeClause === null) return;
    form.setValue('operative_clause', generatedOperativeClause, {
      shouldValidate: true,
      shouldDirty: true,
    });
    operativeClauseGeneratedRef.current = generatedOperativeClause;
  };

  return {
    generatedCoverNoteDesc,
    generatedOperativeClause,
    resetCoverNoteDescToDefault,
    resetOperativeClauseToDefault,
  };
}
