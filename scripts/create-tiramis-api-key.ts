import { randomBytes } from 'node:crypto';

import dataSource from '../apps/tiramis/src/database/data-source';
import { TiramisApiKeyEntity } from '../apps/tiramis/src/modules/api-keys/entities/tiramis-api-key.entity';
import { TiramisApiKeyAuditEntity } from '../apps/tiramis/src/modules/api-keys/entities/tiramis-api-key-audit.entity';

function readArg(name: string, fallback?: string): string | undefined {
  const prefix = `--${name}=`;
  const value = process.argv.find((arg) => arg.startsWith(prefix));
  return value ? value.slice(prefix.length).trim() : fallback;
}

async function main() {
  const name = readArg('name', 'Insurance Portal Service');
  const serviceName = readArg('service', 'insurance-portal-service');
  const tenantCompanyCode = readArg('company-code', undefined);
  const tenantSystemCode = readArg('system-code', undefined);
  const tenantEnvironment = readArg('environment', undefined);
  const expiresAtValue = readArg('expires-at', undefined);
  const scopes = (
    readArg(
      'scopes',
      'tiramis:admin,tiramis:prepare,tiramis:submit,tiramis:read,tiramis:verify,tiramis:retry,tiramis:invoke',
    ) ?? ''
  )
    .split(',')
    .map((scope) => scope.trim())
    .filter(Boolean);

  await dataSource.initialize();
  try {
    const apiKey = `tms_${randomBytes(32).toString('base64url')}`;
    const repository = dataSource.getRepository(TiramisApiKeyEntity);
    const saved = await repository.save(
      repository.create({
        name,
        serviceName,
        tenantCompanyCode: tenantCompanyCode || null,
        tenantSystemCode: tenantSystemCode || null,
        tenantEnvironment: tenantEnvironment || null,
        apiKey,
        keyPrefix: apiKey.slice(0, 18),
        scopes,
        description: 'Generated by scripts/create-tiramis-api-key.ts',
        isActive: true,
        expiresAt: expiresAtValue ? new Date(expiresAtValue) : null,
        revokedAt: null,
        lastUsedAt: null,
      }),
    );

    await dataSource.getRepository(TiramisApiKeyAuditEntity).save({
      apiKeyId: saved.id,
      action: 'CREATED',
      outcome: 'SUCCESS',
      serviceName,
      metadata: { source: 'cli', scopes },
    });

    console.log(`API key id: ${saved.id}`);
    console.log(`Service: ${serviceName}`);
    console.log(`Company code: ${tenantCompanyCode || ''}`);
    console.log(`System code: ${tenantSystemCode || ''}`);
    console.log(`Environment: ${tenantEnvironment || ''}`);
    console.log(`Scopes: ${scopes.join(',')}`);
    console.log(`API key: ${apiKey}`);
  } finally {
    await dataSource.destroy();
  }
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
